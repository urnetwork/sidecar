// Plants each library in its module and an import of the first behind the constraint, and reads the module rule.
func plantIosExtensionLibrary(t *testing.T, constraintLine string, planted ...plantedIosExtensionLibrary) []string {
	t.Helper()
	fixture := newFixture(t)
	fixture.keepLegs(iosExtensionLegName)
	required := map[string]bool{}
	for _, library := range planted {
		fixture.writeSibling(path.Join(library.sibling, library.directory, library.packageName+".go"), "package "+library.packageName+"\n")
		if !required[library.modulePath] {
			required[library.modulePath] = true
			fixture.writeSibling(library.sibling+"/go.mod", "module "+library.modulePath+"\n\ngo 1.27.4\n")
			fixture.requireLocal(library.modulePath, library.version, library.sibling)
		}
	}
	fixture.write("planted.go", constraintLine+"package sidecar\n\nimport _ \""+planted[0].importPath()+"\"\n")
	return fixture.open().iosExtensionModuleFindings(t)
}

