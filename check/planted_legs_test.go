// Rewrites the fixture's list as the clean tree's files and extra, sorted.
func writeIosExtensionLegList(fixture *fixture, extra ...string) {
	fixture.t.Helper()
	entries := slices.Sorted(slices.Values(slices.Concat(fixtureIosExtensionLegFiles, extra)))
	fixture.write(iosExtensionLegListPath, fixtureIosExtensionLegListHeader+strings.Join(entries, "\n")+"\n")
}

